    serving_name = f"configs/local_model_gpu{gpu}.json" if gpu != 5 else "configs/local_model.json"
    server_name = f".local/local_model_server_gpu{gpu}.json" if gpu != 5 else ".local/local_model_server.json"
    serving = json.loads((root / serving_name).read_text())
    if serving["model"] != baseline["model"] or serving["revision"] != baseline["model_revision"]:
        raise ValueError("Existing replica is not the pinned baseline")
    source = root / "sources/deepfri_contract_audit_2026-10-15"
    contract_name = "configs/local_deepfri_sparse_confidence_output_contract_proposed.json"
    if (root / contract_name).exists():
        raise FileExistsError("Preserve existing prospective output contract")
    write_new(root / contract_name, OUTPUT_CONTRACT)
    outputs = []
    for task_id, (dataset, stem, branch, index) in TASKS.items():
        relative = f"data/catalog_deepfri_tasks/{task_id}"
        directory = root / relative
        code = "EC" if dataset == "EnzymeCommission" else "GO"
        prefix = "zenodo__" + dataset + "__nrPDB-" + code
        fasta_path = source / (prefix + "_test_sequences.fasta")
        list_path = source / (prefix + "_test.txt")
        csv_path = source / (prefix + "_test.csv")
        fasta_hash, list_hash = digest(fasta_path), digest(list_path)
        fasta = read_fasta(fasta_path)
        _, excluded = read_split(csv_path)
        case_ids = [case_id for case_id in list_path.read_text().split() if case_id not in set(excluded)]
        if len(case_ids) != len(set(case_ids)) or any(case_id not in fasta for case_id in case_ids):
            raise ValueError("Released test IDs or complete sequences are inconsistent")
        vocab = vocabulary(source, stem, branch, index)
        # Store repository-relative provenance paths exactly as source preparer.
        vocab["source_annotation_path"] = str(Path(vocab["source_annotation_path"]).relative_to(root))
        vocabulary_name = relative + "/class_vocabulary.json"
        if (root / vocabulary_name).exists():
            if json.loads((root / vocabulary_name).read_text()) != vocab:
                raise ValueError("Existing source vocabulary differs")
        else:
            write_new(root / vocabulary_name, vocab)
        input_name = relative + "/model_inputs.jsonl"
        provenance_name = relative + "/input_provenance.jsonl"
        directory.mkdir(parents=True, exist_ok=True)
